CREATE DATABASE FitnessTracker
GO
USE FitnessTracker
GO

CREATE TABLE Addresses(
Aid INT PRIMARY KEY IDENTITY,
City VARCHAR(50) NOT NULL,
Street VARCHAR(50))

CREATE TABLE Gyms(
Gid INT PRIMARY KEY IDENTITY,
Name VARCHAR(50) NOT NULL,
Aid INT FOREIGN KEY REFERENCES Addresses(Aid));

CREATE TABLE Users(
Uid INT PRIMARY KEY IDENTITY,
Name VARCHAR(50) NOT NULL,
Surname VARCHAR(50),
Gid INT FOREIGN KEY REFERENCES Gyms(Gid));

CREATE TABLE BodyMeasurements(
Bid INT PRIMARY KEY IDENTITY,
MeasurementDate DATE,
WeightKg FLOAT,
Uid INT FOREIGN KEY REFERENCES Users(Uid));

CREATE TABLE Workouts(
Wid INT PRIMARY KEY IDENTITY,
WorkoutDate DATE NOT NULL,
Uid INT FOREIGN KEY REFERENCES Users(Uid));

CREATE TABLE Categories(
Cid INT PRIMARY KEY IDENTITY,
Name VARCHAR(50) NOT NULL);

CREATE TABLE Exercises(
Eid INT PRIMARY KEY IDENTITY,
Name VARCHAR(50) NOT NULL,
Cid INT FOREIGN KEY REFERENCES Categories(Cid));

CREATE TABLE Muscles(
Mid INT PRIMARY KEY IDENTITY,
Name VARCHAR(50) NOT NULL);

--m-n
CREATE TABLE WorkoutExercises(
Wid INT FOREIGN KEY REFERENCES Workouts(Wid),
Eid INT FOREIGN KEY REFERENCES Exercises(Eid),
Sets INT,
Reps INT,
WeightKg FLOAT,
CONSTRAINT pk_WorkoutExercises PRIMARY KEY (Wid, Eid));

--m-n , bench press - more muscles.
CREATE TABLE ExercisesMuscles(
Eid INT FOREIGN KEY REFERENCES Exercises(Eid),
Mid INT FOREIGN KEY REFERENCES Muscles(Mid),
CONSTRAINT pk_ExercisesMuscles PRIMARY KEY (Eid, Mid));


